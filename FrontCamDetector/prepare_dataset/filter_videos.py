'''
This script filters out bad frames from a dataset based on annotations generated by the review video script.
The script reads the annotations, identifies the bad frames, and copies the good frames to a new dataset directory. It handles both RGB images and depth maps, ensuring that the output dataset is clean and ready for further processing.
Author: Daniel Rugge (2025) created with help of Claude Sonnet 3.5
'''

import json
from pathlib import Path
import shutil

def filter_dataset(rotated_dataset, depth_dataset, annotations_dir, clean_dataset):
    clean_dataset.mkdir(exist_ok=True)
    
    # Debug: Check if annotation files exist
    json_files = list(annotations_dir.glob("*_bad_frames.json"))
    print(f"Found {len(json_files)} annotation files in {annotations_dir}")
    
    for json_file in json_files:
        print(f"\nProcessing: {json_file.name}")
        
        with open(json_file) as f:
            data = json.load(f)
        
        # Extract sequence name
        seq_name = Path(data["video_path"]).stem.replace("_comparison", "")
        print(f"Sequence name: {seq_name}")
        
        # Get all bad frames across sections
        bad_frames = set()
        for start, end in data["bad_sections"]:
            bad_frames.update(range(start, end + 1))
        print(f"Bad frames: {sorted(bad_frames)}")
        
        # Process both image and depth directories
        for dataset in [rotated_dataset, depth_dataset]:
            src_dir = dataset / seq_name
            dest_dir = clean_dataset / dataset.name / seq_name
            
            # Debug: Check if source directory exists
            if not src_dir.exists():
                print(f"Warning: Source directory not found - {src_dir}")
                continue
                
            dest_dir.mkdir(parents=True, exist_ok=True)
            print(f"Copying from {src_dir} to {dest_dir}")
            
            # Process files
            files = sorted(src_dir.glob("*"))
            print(f"Found {len(files)} files in {src_dir}")
            
            for i, file in enumerate(files):
                if i not in bad_frames:
                    shutil.copy(file, dest_dir / file.name)
                    print(f"  Copied: {file.name}")
                else:
                    print(f"  Skipped (bad frame): {file.name}")

